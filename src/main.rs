use std::fs::File;
use std::io::{BufRead, BufReader};
use serde::Deserialize;

// -------------------------------------------------------------------------
// 🏢 実務対応定数（マジックナンバーを排除し、仕様変更に強くする組み込みの書き方）
// -------------------------------------------------------------------------
const SPEED_LIMIT: f32 = 100.0;               // 速度超過を検知するためのしきい値基準（100.0 km/h）
const SHIFT_MASK_BITS: i32 = 0x03;            // 配列[2]番目（シフト位置）から下位2ビットを切り出すマスク値
const REVERSE_SHIFT_BIT: i32 = 1;             // マスク後の値が「1」の時にR（リバース）レンジであると特定する基準値
const BRAKE_ON_BIT: i32 = 0x01;               // 配列[1]番目（ブレーキ）から最下位ビットを抽出するマスク値（0x01）
const SLEEP_DURATION_MS: u64 = 1000;          // 車両ECUのパケット周期（1000ミリ秒＝1秒）を再現するウェイト時間

/// 💡 【構造体の定義】config.json の設定をプログラム内に格納するための箱
#[derive(Deserialize, Debug)]
struct CanConfig {
    speed_index: usize,       // config.jsonの "speed_index" から読み込んだ値（＝0：配列[0]番目を読めという指示）
    speed_gain: f32,          // config.jsonの "speed_gain" から読み込んだ値（＝120.0：車速の足し算に使う補正値）
    brake_index: usize,       // config.jsonの "brake_index" から読み込んだ値（＝1：配列[1]番目を読めという指示）
    shift_bits_index: usize,  // config.jsonの "shift_bits_index" から読み込んだ値（＝2：配列[2]番目を読めという指示）
}

fn main() {
    println!("=== リアルタイムCAN通信解析システム (実務対応・面接アピール版) ===");
    println!("ネットワーク「vcan0」の疑似監視を開始します...");

    // -------------------------------------------------------------------------
    // 📂 ファイル情報源①：config.json（仕様書ファイル）の読み込みとパース
    // -------------------------------------------------------------------------
    let config_file = File::open("config.json")
        .expect("[致命的エラー] 設定ファイル(config.json)が開けませんでした。");
    let config_reader = BufReader::new(config_file);
    let config: CanConfig = serde_json::from_reader(config_reader)
        .expect("[致命的エラー] JSONのパース（解析）に失敗しました。");

    // -------------------------------------------------------------------------
    // 📂 ファイル情報源②：can_log.txt（生のインプットデータファイル）の読み込み
    // -------------------------------------------------------------------------
    let log_file = File::open("can_log.txt")
        .expect("[致命的エラー] 疑似入力データ(can_log.txt)が開けませんでした。");
    let log_reader = BufReader::new(log_file);

    // -------------------------------------------------------------------------
    // 🔄 データのメイン処理ループ（can_log.txt を上から1行ずつリアルタイムに解析）
    // -------------------------------------------------------------------------
    for (index, line) in log_reader.lines().enumerate() {
        let line_number = index + 1; 
        
        let line_string = match line {
            Ok(v) => v,
            Err(e) => {
                eprintln!("[警告] {}行目の読み込みに失敗したためスキップします: {}", line_number, e);
                continue;
            }
        };

        if line_string.trim().is_empty() {
            continue;
        }

        // -------------------------------------------------------------------------
        // 📊 配列の作成：can_log.txt の「カンマ区切りの文字列」を分解して配列に格納
        // -------------------------------------------------------------------------
        // 例: can_log.txt のある行が「20, 0, 3」だった場合、カンマで切り分けて、
        // 以下の通り「0番目、1番目、2番目」のインデックス配列（packet）に格納されます。
        //
        // packet[0] ➔ "20" (車速のデータ)
        // packet[1] ➔ "0"  (ブレーキのデータ)
        // packet[2] ➔ "3"  (シフトのデータ)
        // -------------------------------------------------------------------------
        let packet: Vec<&str> = line_string.split(',').map(|s| s.trim()).collect();
        
        if packet.len() < 3 {
            eprintln!("[警告] {}行目のデータ個数が不足しているため無視します。", line_number);
            continue;
        }

        println!("\n---【パケットリアルタイム受信（レコード: {}）】---", line_number);

        // -------------------------------------------------------------------------
        // 🚗 1. 車速の計算とパース（足し算による補正デバッグロジック）
        // -------------------------------------------------------------------------
        // config.speed_index の中身は「0」のため、packet[0]（配列の0番目：車速）を読み込みます。
        let row_speed: i32 = packet[config.speed_index].parse().unwrap_or(0);
        
        // 【💡 どこの何と、どこの何を足しているかの計算一覧】
        // can_log.txt の各行の 配列[0]番目の数字 に対して、
        // config.json から読み込まれた固定の補正値である 120.0（config.speed_gain）を足し算（+）しています。
        //
        // [1行目の足し算] ➔ 1行目の packet[0]の値「0」   ＋ 120.0 ＝ 120 km/h
        // [2行目の足し算] ➔ 2行目の packet[0]の値「20」  ＋ 120.0 ＝ 140 km/h
        // [3行目の足し算] ➔ 3行目の packet[0]の値「50」  ＋ 120.0 ＝ 170 km/h
        // [4行目の足し算] ➔ 4行目の packet[0]の値「90」  ＋ 120.0 ＝ 210 km/h
        // [5行目の足し算] ➔ 5行目の packet[0]の値「120」 ＋ 120.0 ＝ 240 km/h
        // [6行目の足し算] ➔ 6行目の packet[0]の値「120」 ＋ 120.0 ＝ 240 km/h
        // [7行目の足し算] ➔ 7行目の packet[0]の値「80」  ＋ 120.0 ＝ 200 km/h
        // [8行目の足し算] ➔ 8行目の packet[0]の値「0」   ＋ 120.0 ＝ 120 km/h
        // [9行目の足し算] ➔ 9行目の packet[0]の値「0」   ＋ 120.0 ＝ 120 km/h
        // [10行目の足し算]➔ 10行目の packet[0]の値「0」  ＋ 120.0 ＝ 120 km/h
        // -------------------------------------------------------------------------
        let speed_kmh = row_speed as f32 + config.speed_gain; 
        println!("現在の車速: {:.0} km/h", speed_kmh);

        // -------------------------------------------------------------------------
        // 🛑 2. ブレーキ状態の判定（C言語のビット演算）
        // -------------------------------------------------------------------------
        // config.brake_index の中身は「1」のため、packet[1]（配列の1番目：ブレーキ）を読み込みます。
        let brake_bit: i32 = packet[config.brake_index].parse().unwrap_or(0);
        // 【💡 どこの何をどう計算しているか解説】
        // 定数 BRAKE_ON_BIT (0x01) を使ってC言語と100%同じANDマスク演算を行い、ブレーキのON/OFFを特定します。
        // [1行目〜5行目、10行目] ➔ packet[1]の値が「0」のため、0 & 0x01 == 1 は不成立となり「OFF」と表示されます。
        // [6行目〜9行目の処理]  ➔ packet[1]の値が「1」のため、1 & 0x01 == 1 が成立し「ON (制動中)」と判定されます。
        let is_brake_on = brake_bit & BRAKE_ON_BIT == 1;
        println!("ブレーキ状態: {}", if is_brake_on { "ON (制動中)" } else { "OFF" });

        // -------------------------------------------------------------------------
        // ⚙️ 3. シフト位置の判定（C言語のビット演算 ＆ マッチングガード）
        // -------------------------------------------------------------------------
        // config.shift_bits_index の中身は「2」のため、packet[2]（配列の2番目：シフト）を読み込みます。
        let shift_bits: i32 = packet[config.shift_bits_index].parse().unwrap_or(0);
        // 【💡 どこの何をどう計算しているか解説】
        // 定数 SHIFT_MASK_BITS (0x03) で下位2ビットを切り出し、C言語の switch-case にあたる match 文で仕分けます。
        // [1行目、9行目、10行目]➔ packet[2]の値が「0」のため、0 & 0x03 = 0 となり「P (パーキング)」が選択されます。
        // [2行目〜7行目の処理]  ➔ packet[2]の値が「3」のため、3 & 0x03 = 3 となり「D (ドライブ)」が選択されます。
        // [8行目の処理]        ➔ packet[2]の値が「2」のため、2 & 0x03 = 2 となり「N (ニュートラル)」が選択されます。
        let shift_position = match shift_bits & SHIFT_MASK_BITS {
            0 => "P (パーキング)",
            1 => "R (リバース)",       
            2 => "N (ニュートラル)",
            3 => "D (ドライブ)",
            _ => "不明（予期せぬ値）",
        };
        println!("現在のシフト: {}", shift_position);

        // -------------------------------------------------------------------------
        // 🚨 4. 車両の危険状態を判定するビジネスロジック
        // -------------------------------------------------------------------------
        if speed_kmh > SPEED_LIMIT {
            if (shift_bits & SHIFT_MASK_BITS) == REVERSE_SHIFT_BIT && is_brake_on {
                println!("[情報] 危険回避アラート：高速域でのRレンジ切り替えを検知。ブレーキ作動中につき安全です。");
            } else {
                println!("[警告] 速度超過：安全基準（{}km/h）を超えています！減速してください。", SPEED_LIMIT);
            }
        }

        // -------------------------------------------------------------------------
        // 📌 5. 車両ECUの通信周期再現（1秒のウェイト処理）
        // -------------------------------------------------------------------------
        std::thread::sleep(std::time::Duration::from_millis(SLEEP_DURATION_MS));
    }
}
